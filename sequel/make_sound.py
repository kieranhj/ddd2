"""Make the sequel's sound data (step 6).

    python sequel/make_sound.py

Writes sequel/build/sfx_data.6502 - the effects as 50 Hz ramps for src/lib/sfx50.6502, fitted by
the kit's sfx50.py (--pad-end) to data/sfx_capture.json, the MOS's own playing of the original's
SOUND and ENVELOPE calls (tools/sfxcapture.mjs data/sfx_effects.json, B-DFS1.2) - and
sequel/build/sound_pitch.6502 (the pitch tables) and sound_tune.6502 (the tune):
  pitch_lo/hi   the MOS's pitch to the chip's period: base[P MOD 48] >> (P DIV 48), from
                data/mos_pitch_period.json (every pitch 1-125 and the tune's, captured the same
                way: exact for each; pitch 0, never written by the MOS from silence, by the rule)
  tune_pitch    the tune's 28 pitches
  tune_notes    DENIS2's tune (src/denis2.6502 tune_data_4204, 226 notes): byte 0 = the first
                pitch's index | (duration - 1) << 5 | &80 when the second pitch is the same,
                else byte 1 = the second's index; &7F ends it
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
KIT = os.environ.get('BEEB_PORT_KIT', os.path.join(ROOT, '..', '..', 'Repos', 'beeb-port-kit'))
BS = chr(92)


def main():
    out = os.path.join(HERE, 'build')
    os.makedirs(out, exist_ok=True)
    env = dict(os.environ, PYTHONPATH=os.path.join(KIT, 'py'))
    subprocess.run([sys.executable, '-m', 'beeb_port_kit.sfx50', os.path.join(ROOT, 'data', 'sfx_capture.json'),
                    os.path.join(out, 'sfx_data.6502'), '--pad-end'], check=True, env=env, stdout=subprocess.DEVNULL)
    s = open(os.path.join(ROOT, 'src', 'denis2.6502')).read()
    i, j = s.index('.tune_data_4204'), s.index('.unused_44ad')
    vals = [int(x, 16) for x in re.findall(r'&([0-9A-F]{2})', s[i:j])]
    notes = [tuple(vals[k:k + 3]) for k in range(0, len(vals), 3)]
    notes = notes[:notes.index((0, 0, 0))]
    pitches = sorted(set(p for n in notes for p in n[:2]))
    assert len(pitches) < 31 and all(1 <= n[2] <= 4 for n in notes)
    data = []
    for p1, p2, d in notes:
        a = pitches.index(p1) | ((d - 1) << 5)
        data += [a | 0x80] if p1 == p2 else [a, pitches.index(p2)]
    data.append(0x7F)
    per = {int(k): v for k, v in json.load(open(os.path.join(ROOT, 'data', 'mos_pitch_period.json'))).items()}
    base = [per[48] * 2] + [per[p] for p in range(1, 48)]
    assert all(base[p % 48] >> (p // 48) == v for p, v in per.items())
    hexs = lambda vs: ', '.join('&%02X' % v for v in vs)
    # the period's high byte is 3 for the first PITCH_HI3 bases, 2 after: sound.6502 works it out
    # (no table: decision 46's RAM)
    hi3 = sum(1 for b in base if b >> 8 == 3)
    assert [b >> 8 for b in base] == [3] * hi3 + [2] * (48 - hi3), [b >> 8 for b in base]
    L = [BS + ' sound_pitch.6502 - GENERATED by sequel/make_sound.py; do not edit. For page &0D\'s tail.', '',
         'PITCH_HI3 = %d    %s the period\'s high byte: 3 below this base, 2 from it' % (hi3, BS),
         '.pitch_lo   EQUB ' + hexs([b & 255 for b in base[:24]]),
         '           EQUB ' + hexs([b & 255 for b in base[24:]])]
    open(os.path.join(out, 'sound_pitch.6502'), 'w', newline='\n').write('\n'.join(L) + '\n')
    TP = [BS + ' sound_tunep.6502 - GENERATED by sequel/make_sound.py; do not edit. For page 2 (&0236).',
          '.tune_pitch EQUB ' + ', '.join(str(p) for p in pitches)]
    open(os.path.join(out, 'sound_tunep.6502'), 'w', newline='\n').write('\n'.join(TP) + '\n')
    T = [BS + ' sound_tune.6502 - GENERATED by sequel/make_sound.py; do not edit.']
    for k in range(0, len(data), 16):
        T.append(('.tune_notes ' if k == 0 else '           ') + 'EQUB ' + hexs(data[k:k + 16]))
    open(os.path.join(out, 'sound_tune.6502'), 'w', newline='\n').write('\n'.join(T) + '\n')
    print('wrote sound_pitch.6502, sound_tune.6502: %d notes in %d bytes, %d pitches; sfx_data.6502' % (len(notes), len(data), len(pitches)))


if __name__ == '__main__':
    main()
