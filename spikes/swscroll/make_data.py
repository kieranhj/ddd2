"""Make the software-scroll spike's data: the original's sprites, column-major, and a course.

    python spikes/swscroll/make_data.py      (after .\\build.ps1 has made build/ddd.ssd)

Writes spikes/swscroll/build/data.6502. The sprites are read out of OUR rebuilt DENIS3 (byte
identical to the STH disc's, tools/compare.py) at the addresses in build/ddd.symbols.json, and
transposed from the original's row-major 4 bytes x 16 lines to 4 columns x 16 bytes, so one
screen column of a sprite is 16 consecutive bytes.

The course is NOT the original's levels - that is a later step (capture them from the original
running). It is a seeded stand-in with the original's object sizes: 8x16-pixel obstacles (4
columns) on the two character rows above the ground, and 16-pixel holes (8 columns) in it,
spaced 20-48 columns apart.
"""
import json
import os
import random
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(os.path.dirname(__file__), 'build', 'data.6502')

COURSE_END = 8000       # columns; the spike stops each strip there
HOLE = 0x80


def denis3():
    img = open(os.path.join(ROOT, 'build', 'ddd.ssd'), 'rb').read()
    s0, s1 = img[0:256], img[256:512]
    for i in range(s1[5] // 8):
        name = s0[8 + i * 8:8 + i * 8 + 7].decode('ascii').rstrip()
        if name != 'DENIS3':
            continue
        e = s1[8 + i * 8:16 + i * 8]
        load = e[0] | e[1] << 8
        length = e[4] | e[5] << 8 | ((e[6] >> 4) & 3) << 16
        sector = e[7] | (e[6] & 3) << 8
        return load, img[sector * 256:sector * 256 + length]
    sys.exit('DENIS3 not in build/ddd.ssd - run .\\build.ps1 first')


def find_symbols(obj, acc):
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, dict) and 'value' in v and isinstance(v['value'], int):
                acc[k] = v['value']
            else:
                find_symbols(v, acc)
    elif isinstance(obj, list):
        for v in obj:
            find_symbols(v, acc)
    return acc


def main():
    load, code = denis3()
    syms = find_symbols(json.load(open(os.path.join(ROOT, 'build', 'ddd.symbols.json'))), {})
    names = ['sprite_land_obstacle_one', 'sprite_land_obstacle_two', 'sprite_land_obstacle_three',
             'sprite_land_player']
    lines = ['\\ data.6502 - GENERATED by spikes/swscroll/make_data.py; do not edit', '']
    for n in names:
        raw = code[syms[n] - load:syms[n] - load + 64]
        col = [raw[line * 4 + c] for c in range(4) for line in range(16)]
        lines.append('.spr_' + n[len('sprite_land_'):])
        for c in range(4):
            lines.append('    EQUB ' + ', '.join('&%02X' % b for b in col[c * 16:c * 16 + 16]))
    rng = random.Random(1984)
    objs, x = [], 100
    while x < COURSE_END:
        t = HOLE if rng.random() < 0.2 else rng.randrange(3)
        objs.append((x, t))
        x += rng.randint(20, 48) + (8 if t == HOLE else 4)
    objs.append((0x7FFF, 0))
    assert len(objs) <= 256
    lines.append('')
    lines.append('NUM_OBJECTS = %d   \\ the last is a sentinel at x = &7FFF' % len(objs))
    for label, f in (('obj_x_lo', lambda o: o[0] & 255), ('obj_x_hi', lambda o: o[0] >> 8),
                     ('obj_type', lambda o: o[1])):
        lines.append('.' + label)
        for i in range(0, len(objs), 16):
            lines.append('    EQUB ' + ', '.join('&%02X' % f(o) for o in objs[i:i + 16]))
    lines.append('')
    lines.append('.col8_lo   \\ screen column * 8')
    for i in range(0, 80, 16):
        lines.append('    EQUB ' + ', '.join('&%02X' % ((c * 8) & 255) for c in range(i, i + 16)))
    lines.append('.col8_hi')
    for i in range(0, 80, 16):
        lines.append('    EQUB ' + ', '.join('&%02X' % ((c * 8) >> 8) for c in range(i, i + 16)))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %s: %d objects (%d holes) to column %d' %
          (OUT, len(objs) - 1, sum(1 for o in objs if o[1] == HOLE), objs[-2][0]))


if __name__ == '__main__':
    main()
